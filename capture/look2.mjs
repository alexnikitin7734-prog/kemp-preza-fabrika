import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(path.join(HERE, '../../pptr/package.json'));
const puppeteer = require('puppeteer-core');
const BASE = 'https://fabrika.content.jarvis-msk.ru/';
const browser = await puppeteer.launch({executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--hide-scrollbars']});
const page = await browser.newPage();
await page.setViewport({width: 1600, height: 1000});
await page.goto(BASE, {waitUntil: 'networkidle2'});
await page.type('input[name=login]', process.env.FL);
await page.type('input[name=password]', process.env.FP);
await Promise.all([page.waitForNavigation({waitUntil: 'networkidle2'}), page.click('button')]);
await page.goto(BASE + '?site=8f763b1a&step=6', {waitUntil: 'networkidle2'});
await new Promise((r) => setTimeout(r, 2500));
const row = await page.evaluateHandle(() => [...document.querySelectorAll('main *')].find((e) => e.childElementCount < 6 && /СТИЛЬ ХУДОЖНИКА/i.test(e.innerText || '') && e.getBoundingClientRect().height < 70 && e.getBoundingClientRect().height > 30));
console.log('row', await row.evaluate((e) => e.outerHTML.slice(0, 400)));
await row.click();
await new Promise((r) => setTimeout(r, 800));
await page.screenshot({path: path.join(HERE, 'look-6dd.png')});
console.log(await page.evaluate(() => { const o = document.querySelector('[role=listbox], .dd-list, .dd-menu, ul'); return o ? o.outerHTML.slice(0, 800) : 'none'; }));
await page.goto(BASE + '?site=8f763b1a&step=5', {waitUntil: 'networkidle2'});
await new Promise((r) => setTimeout(r, 2500));
await page.screenshot({path: path.join(HERE, 'look-step5.png')});
console.log(await page.evaluate(() => [...document.querySelectorAll('main button')].slice(0, 30).map((b) => (b.getAttribute('aria-label') || b.title || b.textContent).trim()).join(' | ')));
await browser.close();
